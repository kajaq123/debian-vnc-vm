#!/usr/bin/env bash
# build-vm.sh -- create the Debian 12 VM disk and cloud-init seed (direct QEMU).
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$SCRIPT_DIR/lib/common.sh"

IMAGE_URL="${VM_IMAGE_URL:-https://cloud.debian.org/images/cloud/bookworm/latest/debian-12-genericcloud-amd64.qcow2}"
IMAGE_SHA256_URL="${VM_IMAGE_SHA256_URL:-${IMAGE_URL}.SHA256SUMS}"
VM_NAME="${VM_NAME:-debian12}"
VM_DIR="${VM_DIR:-$HOME/vms/debian12}"
VM_DISK="${VM_DISK:-$VM_DIR/disk.qcow2}"
VM_SSH_KEY="${VM_SSH_KEY:-$HOME/.ssh/id_ed25519.pub}"
VM_VNC_BIND="${VM_VNC_BIND:-127.0.0.1}"
VM_VNC_PORT="${VM_VNC_PORT:-5901}"
VM_CORES="${VM_CORES:-4}"
VM_MEM="${VM_MEM:-8192}"
NET_MODE="${NET_MODE:-user}"
BRIDGE_IF="${BRIDGE_IF:-br0}"
SSH_HOST_PORT="${SSH_HOST_PORT:-2222}"

usage() { sed -n '2,20p' "$0"; }
while [ $# -gt 0 ]; do
  case "$1" in
    --vm-name) VM_NAME="$2"; shift 2 ;;
    --vm-dir) VM_DIR="$2"; shift 2 ;;
    --disk) VM_DISK="$2"; shift 2 ;;
    --ssh-key) VM_SSH_KEY="$2"; shift 2 ;;
    --vnc-bind) VM_VNC_BIND="$2"; shift 2 ;;
    --vnc-port) VM_VNC_PORT="$2"; shift 2 ;;
    --cores) VM_CORES="$2"; shift 2 ;;
    --mem) VM_MEM="$2"; shift 2 ;;
    --net-mode) NET_MODE="$2"; shift 2 ;;
    --bridge-if) BRIDGE_IF="$2"; shift 2 ;;
    --ssh-host-port) SSH_HOST_PORT="$2"; shift 2 ;;
    --image-url) IMAGE_URL="$2"; shift 2 ;;
    --reset) DO_RESET=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) die_usage "$0" "unknown option: $1" "[--vm-name NAME] [--vm-dir DIR] ...";;
  esac
done

require qemu-img "apt install qemu-utils"
require genisoimage "apt install genisoimage"
[ -r "$VM_SSH_KEY" ] || die "SSH pubkey not found: $VM_SSH_KEY (ssh-keygen -t ed25519)"

BASE_DIR="$VM_DIR/base"
SEED_DIR="$VM_DIR/seed"
IMAGE_FILE="$BASE_DIR/debian-12-genericcloud-amd64.qcow2"
SEED_ISO="$VM_DIR/seed.iso"
mkdir -p "$BASE_DIR" "$SEED_DIR" "$(dirname "$VM_DISK")"

if [ -e "$VM_DISK" ]; then
  [ "${DO_RESET:-0}" -eq 1 ] || die "disk exists: $VM_DISK (use --reset)"
  rm -f "$VM_DISK"
fi

if [ ! -f "$IMAGE_FILE" ]; then
  log "downloading Debian 12 cloud image"
  curl -fL --retry 3 --progress-bar -o "$IMAGE_FILE.part" "$IMAGE_URL"
  mv "$IMAGE_FILE.part" "$IMAGE_FILE"
fi
if curl -fsSL --retry 2 -o "$BASE_DIR/SHA256SUMS" "$IMAGE_SHA256_URL" 2>/dev/null; then
  if (cd "$BASE_DIR" && grep -F "$(basename "$IMAGE_FILE")" SHA256SUMS | sha256sum -c - >/dev/null 2>&1); then
    log "base image checksum OK"
  else
    warn "checksum verify skipped/failed"
  fi
fi

# Render cloud-init user-data
PUBKEY="$(cat "$VM_SSH_KEY")"
export VM_USER="${VM_USER:-kamil}" VM_SSH_PUBKEY="$PUBKEY" \
       VM_VNC_PASSWD="${VM_VNC_PASSWD:-changeme}" VM_VNC_RESOLUTION="${VM_VNC_RESOLUTION:-1280x800}" \
       NV_FLAG="${NV_FLAG:-skip}"
python3 "$SCRIPT_DIR/render-cloud-init.py" \
  --user "$VM_USER" --pubkey "$VM_SSH_KEY" \
  --vnc-passwd "$VM_VNC_PASSWD" --vnc-resolution "$VM_VNC_RESOLUTION" \
  --nvidia-flag "$NV_FLAG" --template "$SCRIPT_DIR/../guest/user-data.yaml.tmpl" \
  --output "$SEED_DIR/user-data" --vm-conf "$VM_DIR/vm.conf"
cp "$SCRIPT_DIR/../guest/meta-data" "$SEED_DIR/meta-data"

log "building seed ISO"
rm -f "$SEED_ISO"
genisoimage -quiet -output "$SEED_ISO" -volid cidata -joliet -rock "$SEED_DIR/user-data" "$SEED_DIR/meta-data"

log "creating overlay disk"
qemu-img create -q -f qcow2 -F qcow2 -b "$IMAGE_FILE" "$VM_DISK"

cat > "$VM_DIR/vm.conf" <<CONF
# Generated by build-vm.sh
VM_NAME=$VM_NAME
VM_DIR=$VM_DIR
VM_DISK=$VM_DISK
VM_SSH_KEY=$VM_SSH_KEY
VM_VNC_BIND=$VM_VNC_BIND
VM_VNC_PORT=$VM_VNC_PORT
VM_CORES=$VM_CORES
VM_MEM=$VM_MEM
NET_MODE=$NET_MODE
BRIDGE_IF=$BRIDGE_IF
SSH_HOST_PORT=$SSH_HOST_PORT
CONF
log "done. Next: scripts/vm-start.sh"
